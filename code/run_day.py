import json
import os
import sys
import time
from functools import lru_cache
from multiprocessing import Pool

import numpy as np
import pandas as pd

import controller as ctl
import netsim as n

SD_FACTOR = 1.5
BG_SLACK = 0.02


@lru_cache(maxsize=None)
def setup(scen, gpus, period_min, hours):
    prm = n.scenario_prm(scen, gpus)
    lam_peak, bg_peak = n.scenario_load(scen, prm)
    n_per = hours * 60 // period_min
    mid = (np.arange(n_per) + 0.5) * period_min / 60
    lam, bg = n.diurnal_at(mid, lam_peak, bg_peak)
    return prm, lam, bg


def decide_task(args):
    t_start = time.time()
    out = _decide_task(args)
    return (*out, time.time() - t_start)


def _decide_task(args):
    scen, gpus, pmin, hours, policy, k, slo = args
    prm0, LAM, BG = setup(scen, gpus, pmin, hours)
    prm = ctl.with_slo(prm0, slo)
    lam, bg = LAM[k], BG[k]
    if policy == "allon":
        cfg, log = ctl.decide_allon(prm, k, lam, bg)
    elif policy == "elastictree":
        kp = (k - 1) % len(LAM)
        cfg, log = ctl.decide_elastictree(prm, k, LAM[kp], BG[kp])
    elif policy == "et_hedera":
        kp = (k - 1) % len(LAM)
        cfg, log = ctl.decide_et_hedera(prm, k, LAM[kp], BG[kp])
    elif policy == "smartfct":
        kp = (k - 1) % len(LAM)
        cfg, log = ctl.decide_smartfct(prm, k, LAM[kp], BG[kp])
    elif policy == "wang22":
        k1, k2 = (k - 1) % len(LAM), (k - 2) % len(LAM)
        cfg, log = ctl.decide_wang22(prm, k, (LAM[k2], LAM[k1]), (BG[k2], BG[k1]))
    elif policy == "oracle":
        cfg, log = ctl.decide_oracle(prm, k, lam, bg)
    elif policy in ctl.LEARNED_POLICIES:
        lam_hat, bg_hat = ctl.forecast(lam, bg, k)
        cfg, log = ctl.decide_ours_learned(prm, scen, gpus, k, lam_hat, bg_hat, policy)
    else:
        lam_hat, bg_hat = ctl.forecast(lam, bg, k)
        cfg, log = ctl.decide_ours(prm, k, lam_hat, bg_hat, policy)
    return policy, k, cfg, log


def hysteresis_task(args):
    scen, gpus, pmin, hours, policy, dec, ks, slo = args
    prm0, LAM, BG = setup(scen, gpus, pmin, hours)
    out, log, kept = ctl.apply_hysteresis(ctl.with_slo(prm0, slo), policy, dec, LAM, BG, ks, scen, gpus)
    return policy, out, log, kept


def eval_task(args):
    scen, gpus, pmin, hours, policy, k, cfg, slo = args
    prm0, LAM, BG = setup(scen, gpus, pmin, hours)
    return ctl.evaluate(ctl.with_slo(prm0, slo), cfg, policy, k, LAM[k], BG[k])


if __name__ == "__main__":
    n_proc = int(sys.argv[1]) if len(sys.argv) > 1 else os.cpu_count()
    hours = int(sys.argv[2]) if len(sys.argv) > 2 else 24
    scen = sys.argv[3] if len(sys.argv) > 3 else "base"
    gpus = int(sys.argv[4]) if len(sys.argv) > 4 else 1024
    pmin = int(sys.argv[5]) if len(sys.argv) > 5 else 60
    assert scen in n.SCENARIOS, f"scenario must be one of {list(n.SCENARIOS)}"
    assert gpus in n.SCALES, f"number of GPUs must be one of {list(n.SCALES)}"
    assert 60 % pmin == 0, "slow-layer period must divide 60 minutes"
    outdir = os.environ.get("RUN_OUTDIR") or f"results_{scen}_{gpus}g_{pmin}m"
    only = [p for p in os.environ.get("ONLY_POLICIES", "").split(",") if p]
    if only:
        missing = [p for p in only if p not in ctl.POLICIES]
        assert not missing, f"unknown policies {missing} (ours_mlp requires {ctl.EVALUATOR}, generated by train_evaluator.py)"
    policies = only or list(ctl.POLICIES)
    os.makedirs(outdir, exist_ok=True)
    t0 = time.time()
    prm0, LAM0, BG0 = setup(scen, gpus, pmin, hours)
    n_per = len(LAM0)
    ks = list(range(n_per))
    n_srv = prm0.n_leaf * prm0.servers_per_leaf
    print(f"Scenario {scen}, {gpus} GPUs ({n_srv} servers, {prm0.n_leaf} leaves, {prm0.n_spine} spines), "
          f"{hours} h, slow-layer period {pmin} min ({n_per} periods), {n_proc} processes, output to {outdir}/", flush=True)
    print(f"  Redundancy constraints: at least {ctl.MIN_SPINES} spines, at least {ctl.MIN_EDGE_PORTS} NIC ports, uplinks U/2 or U (same for all methods)", flush=True)
    print(f"  Peak inference request rate {LAM0.max():.0f} req/s, peak background traffic {BG0.max()/1e12:.2f} TB/s; "
          f"intra-period load fluctuation {'on' if prm0.fluct_on else 'off'}", flush=True)

    with Pool(n_proc) as pool:
        print("Calibration: all-on configuration", flush=True)
        base = pool.map(eval_task, [(scen, gpus, pmin, hours, "allon", k, n.full_cfg(prm0), None) for k in ks])
        sd_worst = max(r["kv_sd_p99"] for r in base)
        bg_worst = min(r["bg_tput"] for r in base)
        slo = dict(slo_kv_sd_p99=round(SD_FACTOR * sd_worst, 3),
                   slo_bg_tput=round(bg_worst - BG_SLACK, 3))
        print(f"  All-on worst: KV P99 slowdown = {sd_worst:.2f}, background throughput ratio = {bg_worst:.3f}", flush=True)
        print(f"  SLO: KV P99 slowdown ≤ {slo['slo_kv_sd_p99']}, background throughput ratio ≥ {slo['slo_bg_tput']}", flush=True)

        tasks = [(scen, gpus, pmin, hours, p, k, slo) for p in policies for k in ks]
        tasks.sort(key=lambda x: (x[4] == "oracle", x[4].startswith("ours")), reverse=True)
        decisions, probes = {}, []
        print(f"Decision phase: {len(tasks)} tasks", flush=True)
        step = max(12, len(tasks) // 10)
        dec_time = {}
        for i, (p, k, cfg, log, t_dec) in enumerate(pool.imap_unordered(decide_task, tasks), 1):
            decisions[(p, k)] = cfg
            probes.extend(log)
            dec_time.setdefault(p, []).append(t_dec)
            if i % step == 0 or i == len(tasks):
                print(f"  {i}/{len(tasks)}  {(time.time()-t0)/60:.1f} min", flush=True)

        print("Hysteresis phase", flush=True)
        print("  Decision time per period (s, single core): " + "; ".join(
            f"{p} mean {np.mean(v):.3f} / max {np.max(v):.3f}" for p, v in dec_time.items()), flush=True)
        pd.DataFrame([dict(policy=p, seconds=t) for p, v in dec_time.items() for t in v]).to_csv(
            f"{outdir}/decide_time.csv", index=False)
        inf = [x["infer_seconds"] for x in probes if x.get("tag") == "learned"]
        if inf:
            print(f"  Learned evaluator: inference time to judge all candidates per period, mean {np.mean(inf) * 1000:.1f} ms / "
                  f"max {np.max(inf) * 1000:.1f} ms (excluding the first model load)", flush=True)
        ours = [p for p in policies if p.startswith("ours")]
        hy_tasks = [(scen, gpus, pmin, hours, p, {k: decisions[(p, k)] for k in ks}, ks, slo) for p in ours]
        kept_count = {}
        for p, out, log, kept in pool.map(hysteresis_task, hy_tasks):
            for k in ks:
                decisions[(p, k)] = out[k]
            probes.extend(log)
            kept_count[p] = kept
            print(f"  {p}: {kept} periods kept the previous period's configuration", flush=True)

        print("Evaluation phase", flush=True)
        ev_tasks = [(scen, gpus, pmin, hours, p, k, decisions[(p, k)], slo) for p in policies for k in ks]
        rows = pool.map(eval_task, ev_tasks)

    df = pd.DataFrame(rows)
    df = df.rename(columns={"hour": "period"})
    df["hour"] = df.period * pmin / 60
    df["period_h"] = pmin / 60
    df["scenario"] = scen
    df["gpus"] = gpus
    df = df.sort_values(["policy", "period"])
    df.to_csv(f"{outdir}/day_results.csv", index=False)
    pd.DataFrame(probes).to_csv(f"{outdir}/probe_log.csv", index=False)
    json.dump(dict(scenario=scen, gpus=gpus, period_min=pmin, hours=hours, **slo,
                   allon_worst_kv_sd_p99=sd_worst, allon_worst_bg_tput=bg_worst,
                   hysteresis_kept=kept_count, forecast_err=ctl.FORECAST_ERR, sd_margin=ctl.SD_MARGIN,
                   bg_extra=ctl.BG_EXTRA, ar_margin=ctl.AR_MARGIN, hysteresis=ctl.HYSTERESIS,
                   spine_tol=ctl.SPINE_TOL, nvlink_knob=ctl.NVLINK_KNOB,
                   min_spines=ctl.MIN_SPINES, min_edge_ports=ctl.MIN_EDGE_PORTS,
                   fluct=dict(on=prm0.fluct_on, n_seg=prm0.fluct_n_seg, sigma=prm0.fluct_sigma,
                              burst_p=prm0.fluct_burst_p, burst_x=prm0.fluct_burst_x, bg_sigma=prm0.fluct_bg_sigma)),
              open(f"{outdir}/slo.json", "w"), indent=1, ensure_ascii=False)
    print(f"Done in {(time.time()-t0)/60:.1f} min; {len(probes)} probe records")
